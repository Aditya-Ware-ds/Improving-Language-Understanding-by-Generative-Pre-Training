"""Assemble report/report.md from report/report_template.md + results/, then convert with pandoc.

Every number in the finished report comes from results/*.json or results/tables/*.md (written by
make_report_assets.py). Nothing is typed in by hand: a run that has not been done shows up as
"not run" instead of a value.

Template syntax
  {{key}}                       a value computed in values()
  <!--TABLE:name-->             contents of results/tables/name.md
  <!--FIG:file.png|caption-->   the figure results/figures/file.png (or a "not generated" note)
  <!--AUTO:name-->              a paragraph generated by auto_<name>()

    python src/build_report.py            # report.md + report.docx (+ report.pdf if a LaTeX engine exists)
    python src/build_report.py --no-docx  # markdown only
"""
