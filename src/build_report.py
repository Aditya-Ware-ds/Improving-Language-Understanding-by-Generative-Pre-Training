def auto_attention():
    a = jload("tables/attention_sentence.json")
    if not a:
        return "*Attention map available after E1 has been run (`make_report_assets.py --attention`).*"
    toks, row = a["tokens"], np.array(a["e_row_last_layer"])
    order = [i for i in np.argsort(-row) if 0 < i < len(toks) - 1][:4]
    top = ", ".join(f"“{toks[i]}” ({row[i]:.2f})" for i in order)
    return (f"For the sentence *“{a['sentence']}”*, the ⟨e⟩ token in the last layer places its largest attention "
            f"weights (averaged over heads, excluding ⟨s⟩ and ⟨e⟩) on {top}. The weight on ⟨s⟩ is "
            f"{row[0]:.2f}; heavy attention to the first token is a well-known \"attention sink\" pattern and is not "
            f"by itself evidence that the token matters. Attention weights are a diagnostic, not an explanation.")


def auto_curves():
    out = []
    for task in ("sst2", "mrpc"):
        for r in load(f"E1_{task}_seed42.json"):
            c = r["curves"]
            if not c["val_acc"]:
                continue
            best = int(np.argmax(c["val_acc"]))
            gap = c["train_acc"][-1] - c["val_acc"][-1]
            vmin = int(np.argmin(c["val_loss"]))
            out.append(f"- **{task.upper()} (E1, seed 42):** best validation accuracy {100 * c['val_acc'][best]:.2f}% at "
                       f"epoch {c['epoch'][best]:.2f}, final {100 * c['val_acc'][-1]:.2f}%; validation loss is lowest at "
                       f"epoch {c['epoch'][vmin]:.2f} and ends at {c['val_loss'][-1]:.3f} "
                       f"({'rising after its minimum, a mild sign of over-confidence' if vmin < len(c['val_loss']) - 1 else 'still at its minimum'}). "
                       f"Final train–validation accuracy gap: {100 * gap:.1f} points. We report the final-epoch model "
                       f"(no checkpoint selection on the validation set).")
    return "\n".join(out) or "*Curves available after E1 has been run.*"


NOISE = {"sst2": 0.5, "mrpc": 1.0}   # |difference| (points) below which one seed cannot separate two settings


def aux_sentence(task, key):
    e1, e2 = vals("E1", task, key), vals("E2", task, key)
    if not (e1 and e2):
        return "*E1 and E2 are both needed for this comparison.*"
    d = mean(e2) - mean(e1)
    sd = max([np.std(v, ddof=1) for v in (e1, e2) if len(v) > 1] or [0.0])
    thr = max(NOISE[task], sd)
    pd = PAPER[task]["noaux"] - PAPER[task]["full"]
    metric = "accuracy" if key == "accuracy" else "F1"
    s = (f"Removing the auxiliary objective (λ = 0) changes {metric} by {sgn(d)} points "
         f"({f2(mean(e1))} → {f2(mean(e2))}; paper, Table 5: {PAPER[task]['full']} → {PAPER[task]['noaux']}, "
         f"{sgn(pd)}). ")
    if abs(d) < thr:
        s += (f"This is within what seed-to-seed variation alone produces (≈{thr:.1f} points), so on {task.upper()} "
              f"we see no measurable benefit from the auxiliary loss, consistent with the paper's remark that "
              f"smaller datasets do not benefit from it.")
    elif d > 0:
        s += ("As in the paper, the model is better without the auxiliary loss on this dataset.")
    else:
        s += ("Unlike the paper's ablation on this dataset, the auxiliary loss helped in our runs.")
    return s


def auto_aux_discussion():
    return " ".join(f"**{t.upper()}:** {aux_sentence(t, k)}" for t, k in (("sst2", "accuracy"), ("mrpc", "f1_pos")))


def ablation_drops(task, key):
    e1 = mean(vals("E1", task, key))
    if e1 is None:
        return None
    d = {}
    for x, lab in (("E2", "no auxiliary LM"), ("E3", "no pre-training")):
        v = mean(vals(x, task, key))
        if v is not None:
            d[lab] = e1 - v
    return d


def auto_pretrain_discussion():
    out = []
    for t, k, name in (("sst2", "accuracy", "accuracy"), ("mrpc", "accuracy", "accuracy")):
        d = ablation_drops(t, k)
        if not d or "no pre-training" not in d:
            continue
        largest = max(d, key=lambda z: d[z])
        out.append(f"On {t.upper()}, removing pre-training costs {d['no pre-training']:.2f} points of {name}"
                   + (", the largest drop of our ablations, as in the paper." if largest == "no pre-training"
                      else f", less than removing the {largest} ({d[largest]:.2f}), unlike the paper."))
    pts = sorted([(r["setting"]["transfer_layers"], 100 * r["metrics"]["accuracy"]) for r in load("E6_mrpc_k*_seed42.json")]
                 + [(12, 100 * r["metrics"]["accuracy"]) for r in load("E1_mrpc_seed42.json")])
    if len(pts) >= 3:
        gain = pts[-1][1] - pts[0][1]
        out.append(f"The layer-transfer runs (E6) refine this: going from embeddings only (k = {pts[0][0]}) to all "
                   f"{pts[-1][0]} blocks changes MRPC accuracy by {sgn(gain)} points"
                   + (", so the useful knowledge is spread over the depth of the network and not only in the "
                      "embeddings, as in the paper's Fig. 2 (left)." if gain > NOISE["mrpc"] else
                      ", which is too small to separate from noise on 408 validation pairs with one seed."))
    return " ".join(out) or "*Our corresponding measurements appear here once E1, E3 and E6 have been run.*"


def auto_baseline_discussion():
    out = []
    for t, k in (("sst2", "accuracy"), ("mrpc", "accuracy")):
        b, e1, e3 = load(f"E4_tfidf_lr_{t}.json"), mean(vals("E1", t, k)), mean(vals("E3", t, k))
        if b and e1 is not None:
            bv = 100 * b[0]["metrics"][k]
            s = f"On {t.upper()} the baseline reaches {bv:.2f}% accuracy against {e1:.2f}% for GPT-1 ({sgn(e1 - bv)})"
            if e3 is not None:
                s += f", while the randomly initialised Transformer reaches {e3:.2f}% ({sgn(e3 - bv)} relative to the baseline)"
            out.append(s + ".")
    return " ".join(out) or "*Measured comparison appears once E1 and E4 have been run.*"


def auto_zeroshot_discussion():
    z = load("E5_zeroshot_sst2.json")
    if not z:
        return "*Our zero-shot measurement appears here once E5 has been run.*"
    z = z[0]
    acc, maj = 100 * z["metrics"]["accuracy"], 100 * z["chance_majority_acc"]
    diag = 100 * z["diagnostic_median_threshold"]["metrics"]["accuracy"]
    e1 = mean(vals("E1", "sst2", "accuracy"))
    s = (f"With the paper's exact heuristic our model scores {acc:.2f}% against a majority-class rate of {maj:.2f}%"
         + (", i.e. above chance without ever seeing a label" if acc > maj + 2 else
            ", i.e. not clearly above chance with the fixed decision rule"))
    s += (f"; with the bias-corrected threshold it reaches {diag:.2f}%, "
          + ("which shows that the log-odds do carry sentiment information." if diag > maj + 5 else
             "so the sentiment signal in the raw LM is weak.") )
    if e1 is not None:
        s += f" Fine-tuning (E1, {e1:.2f}%) remains far better."
    return s


def auto_conclusion():
    rows = []
    d_s = ablation_drops("sst2", "accuracy") or {}
    d_m = ablation_drops("mrpc", "accuracy") or {}
    def verdict(ok, msg_ok, msg_no, have):
        if not have:
            return "not tested (runs missing)"
        return msg_ok if ok else msg_no
    have = "no pre-training" in d_s or "no pre-training" in d_m
    ok = all(v.get("no pre-training", -1) >= max(v.values()) for v in (d_s, d_m) if "no pre-training" in v)
    rows.append(("Pre-training is the most important ingredient", verdict(ok, "reproduced", "not reproduced", have)))
    pts = sorted([(r["setting"]["transfer_layers"], 100 * r["metrics"]["accuracy"]) for r in load("E6_mrpc_k*_seed42.json")]
                 + [(12, 100 * r["metrics"]["accuracy"]) for r in load("E1_mrpc_seed42.json")])
    rows.append(("Transferring more pre-trained layers helps",
                 verdict(len(pts) >= 3 and pts[-1][1] - pts[0][1] > NOISE["mrpc"], "reproduced (overall trend)",
                         "not clearly reproduced", len(pts) >= 3)))
    aux = []
    for t, k in (("sst2", "accuracy"), ("mrpc", "f1_pos")):
        e1, e2 = vals("E1", t, k), vals("E2", t, k)
        if e1 and e2:
            aux.append(mean(e2) - mean(e1) > -NOISE[t])
    rows.append(("Auxiliary LM loss gives no gain on small datasets such as SST-2/MRPC",
                 verdict(all(aux), "reproduced", "not reproduced (it helped in our runs)", bool(aux))))
    z = load("E5_zeroshot_sst2.json")
    zok = bool(z) and 100 * z[0]["diagnostic_median_threshold"]["metrics"]["accuracy"] > 100 * z[0]["chance_majority_acc"] + 5
    rows.append(("The pre-trained LM carries task knowledge zero-shot",
                 verdict(zok, "reproduced (above chance)", "only weakly / not reproduced", bool(z))))
    return "| Paper's conclusion | Our result |\n|---|---|\n" + "\n".join(f"| {a} | {b} |" for a, b in rows)


# ----------------------------------------------------------------------------- assembly
def build(no_docx=False):
    with open(os.path.join(REP, "report_template.md"), encoding="utf-8") as f:
        text = f.read()
    V = values()
    text = re.sub(r"\{\{(\w+)\}\}", lambda m: V.get(m.group(1), f"{{{{{m.group(1)}}}}}"), text)

    def table(m):
        p = os.path.join(RES, "tables", m.group(1) + ".md")
        if os.path.exists(p):
            with open(p, encoding="utf-8") as f:
                return f.read().strip()
        return f"*Table `{m.group(1)}` not generated yet: run the experiments, then `python src/make_report_assets.py`.*"

    def fig(m):
        name, cap = m.group(1), m.group(2)
        if os.path.exists(os.path.join(RES, "figures", name)):
            return f"![{cap}](../results/figures/{name}){{width=100%}}"
        return f"*Figure `{name}` not generated yet ({cap}).*"

    text = re.sub(r"<!--TABLE:(\w+)-->", table, text)
    text = re.sub(r"<!--FIG:([\w.\-]+)\|(.*?)-->", fig, text)
    text = re.sub(r"<!--AUTO:(\w+)-->", lambda m: globals()[f"auto_{m.group(1)}"](), text)
    out_md = os.path.join(REP, "report.md")
    with open(out_md, "w", encoding="utf-8") as f:
        f.write(text)
    missing = text.count(NA) + text.count("not generated yet") + text.count("not done yet")
    print(f"wrote report/report.md ({len(text.split()):,} words; {missing} placeholders for runs not done)")
    if no_docx:
        return
    if not shutil.which("pandoc"):
        print("pandoc not found: install it to produce report.docx")
        return
    cmd = ["pandoc", "report.md", "-o", "report.docx", "--toc", "--resource-path=.:..",
           "--metadata", "link-citations=true"]
    ref = os.path.join(REP, "reference.docx")
    if os.path.exists(ref):
        cmd += ["--reference-doc", "reference.docx"]
    subprocess.run(cmd, cwd=REP, check=True)
    print("wrote report/report.docx")
    engine = next((e for e in ("xelatex", "lualatex", "pdflatex", "tectonic") if shutil.which(e)), None)
    if engine:
        r = subprocess.run(["pandoc", "report.md", "-o", "report.pdf", "--toc", f"--pdf-engine={engine}",
                            "--resource-path=.:..", "-V", "geometry:margin=2.2cm", "-V", "fontsize=11pt",
                            "-V", "mainfont=DejaVu Serif" if engine != "pdflatex" else "fontsize=11pt"],
                           cwd=REP)
        print("wrote report/report.pdf" if r.returncode == 0 else "PDF conversion failed (docx is still fine)")
    else:
        print("no LaTeX engine found: skipped report.pdf (open report.docx in Word and 'Save as PDF')")


