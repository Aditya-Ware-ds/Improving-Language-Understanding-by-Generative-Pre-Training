def auto_layers():
    pts = [(r["setting"]["transfer_layers"], r) for r in load("E6_mrpc_k*_seed42.json")]
    pts += [(12, r) for r in load("E1_mrpc_seed42.json")]
    if len(pts) < 2:
        return "*Layer-transfer runs not done yet.*"
    pts.sort(key=lambda t: t[0])
    acc = [100 * r["metrics"]["accuracy"] for _, r in pts]
    ks = [k for k, _ in pts]
    mono = all(b >= a - 0.5 for a, b in zip(acc, acc[1:]))
    e3 = load("E3_mrpc_seed42.json")
    s = (f"Accuracy goes from {acc[0]:.2f}% with k = {ks[0]} (only embeddings transferred) to {acc[-1]:.2f}% with "
         f"k = {ks[-1]}, a gain of {acc[-1] - acc[0]:.2f} points. ")
    s += ("The curve rises (almost) monotonically, i.e. every additional block of pre-trained layers helps, "
          "which is the same qualitative trend the paper shows for MultiNLI and RACE (Fig. 2, left). "
          if mono else
          "The curve is not monotonic: with a single seed on a 408-example validation set, differences of one or "
          "two points are within noise (one example = 0.25 points), so only the overall trend should be read. ")
    if e3:
        s += (f"For reference, training everything from scratch (E3, no pre-trained embeddings either) gives "
              f"{100 * e3[0]['metrics']['accuracy']:.2f}%.")
    return s


