# ----------------------------------------------------------------------------- loading helpers
def load(pattern):
    out = []
    for p in sorted(glob.glob(os.path.join(RES, pattern))):
        with open(p, encoding="utf-8") as f:
            r = json.load(f)
        if not r.get("quick"):
            out.append(r)
    return out


def jload(path):
    p = os.path.join(RES, path)
    if os.path.exists(p):
        with open(p, encoding="utf-8") as f:
            return json.load(f)
    return None


def vals(exp, task, key):
    return [100 * r["metrics"][key] for r in load(f"{exp}_{task}_seed*.json")]


def mean(v):
    return float(np.mean(v)) if v else None


def ms(v):
    if not v:
        return NA
    return f"{np.mean(v):.2f}" if len(v) == 1 else f"{np.mean(v):.2f} ± {np.std(v, ddof=1):.2f}"


def f2(x):
    return NA if x is None else f"{x:.2f}"


def sgn(x):
    return f"{x:+.2f}"


# ----------------------------------------------------------------------------- scalar values
def values():
    V = {}
    wm = jload("weight_match.json")
    V["wm_maxdiff"] = f"{wm['max_abs_diff']:.2e}" if wm else NA
    V["wm_status"] = ("passed" if wm and wm["passed"] else "not yet run")
    V["n_params_hf"] = f"{wm['n_parameters_hf']:,}" if wm else NA
    any_run = (load("E1_*.json") + load("E2_*.json") + load("E3_*.json"))
    c = any_run[0]["compute"] if any_run else None
    V["n_params_clf"] = f"{c['n_parameters']:,}" if c else NA
    V["gpu"] = c["gpu"] if c else NA
    V["torch_version"] = c["torch"] if c else NA
    V["tf_version"] = (c.get("transformers") or NA) if c else NA
    V["platform"] = c["platform"] if c else NA
    h = any_run[0]["hyperparams"] if any_run else None
    V["micro_batch"] = str(h["micro_batch"]) if h else NA
    V["grad_accum"] = str(h["grad_accum"]) if h else NA
    oom = sum(len(r.get("oom_events", [])) for r in any_run)
    V["oom_total"] = str(oom)
    V["tok_mode"] = any_run[0]["data"]["tokenizer_mode"] if any_run else NA
    for t in ("sst2", "mrpc"):
        s = jload(f"length_stats_{t}.json")
        V[f"{t}_maxlen"] = str(s["chosen_max_len"]) if s else NA
        V[f"{t}_len_train_mean"] = f"{s['train']['mean']:.1f}" if s else NA
        V[f"{t}_len_val_mean"] = f"{s['validation']['mean']:.1f}" if s else NA
        V[f"{t}_len_train_max"] = str(s["train"]["max"]) if s else NA
        V[f"{t}_n_train"] = str(s["train"]["n"]) if s else NA
        V[f"{t}_n_val"] = str(s["validation"]["n"]) if s else NA
    V["e1_sst2_acc"] = ms(vals("E1", "sst2", "accuracy"))
    V["e1_mrpc_f1"] = ms(vals("E1", "mrpc", "f1_pos"))
    V["e1_mrpc_acc"] = ms(vals("E1", "mrpc", "accuracy"))
    V["mrpc_seeds"] = ", ".join(str(r["hyperparams"]["seed"]) for r in load("E1_mrpc_seed*.json")) or NA
    gpu_min = sum(r["compute"]["train_time_s"] for r in any_run + load("E6_*.json")) / 60
    V["gpu_hours"] = f"{gpu_min / 60:.1f}" if any_run else NA
    peaks = [r["compute"]["peak_vram_mib"] for r in any_run + load("E6_*.json") if r["compute"].get("peak_vram_mib")]
    V["peak_vram_max"] = f"{max(peaks):.0f}" if peaks else NA
    return V


